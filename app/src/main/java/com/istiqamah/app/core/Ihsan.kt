object Ihsan {
    /** দিনে কত রাকাত সুন্নাতে মুয়াক্কাদা (১২-এর মধ্যে) */
    fun rakat(slots: Set<SunnahSlot>): Int = slots.filter { it.twelve }.sumOf { it.rakat }

    /** গত [n] দিনে (আজসহ) পুরো ১২ রাকাত হয়েছে এমন দিন */
    fun fullDays(log: Map<LocalDate, Set<SunnahSlot>>, today: LocalDate, n: Int): Int =
        (0 until n).count { rakat(log[today.minusDays(it.toLong())].orEmpty()) == 12 }

    /** গত [n] দিনে মোট রাকাত / (১২ × n) — শতাংশ */
    fun percent(log: Map<LocalDate, Set<SunnahSlot>>, today: LocalDate, n: Int): Int {
        val sum = (0 until n).sumOf { rakat(log[today.minusDays(it.toLong())].orEmpty()) }
        return if (n <= 0) 0 else (sum * 100 / (12 * n)).coerceIn(0, 100)
    }

    /** টানা কত দিন পুরো ১২ রাকাত (আজ না হলে গতকাল থেকে গোনা) */
    fun streak(log: Map<LocalDate, Set<SunnahSlot>>, today: LocalDate): Int {
        var d = if (rakat(log[today].orEmpty()) == 12) today else today.minusDays(1)
        var n = 0
        while (rakat(log[d].orEmpty()) == 12) { n++; d = d.minusDays(1) }
        return n
    }

    /** একটা নির্দিষ্ট ধরনের (বিতর/তাহাজ্জুদ/দোহা) আমল গত [n] দিনে কত দিন */
    fun countOf(slot: SunnahSlot, log: Map<LocalDate, Set<SunnahSlot>>, today: LocalDate, n: Int): Int =
        (0 until n).count { slot in log[today.minusDays(it.toLong())].orEmpty() }

    /** গত ৭ দিনের দৈনিক গড় খুশু (১–৩), আর সপ্তাহের গড় */
    fun khushuWeek(ratings: Map<LocalDate, Map<Prayer, Int>>, today: LocalDate): KhushuWeek {
        val days = (6 downTo 0).map { i ->
            val d = today.minusDays(i.toLong())
            d to ratings[d]?.values?.takeIf { it.isNotEmpty() }?.average()
        }
        val all = days.mapNotNull { (d, _) -> ratings[d]?.values }.flatten()
        return KhushuWeek(days, all.takeIf { it.isNotEmpty() }?.average(), all.size)
    }

    /**
     * আজ কোন পড়া ওয়াক্তের খুশু এখনো জানানো হয়নি — সবচেয়ে শেষেরটা।
     * শুধু সময়মতো/জামাতে পড়া ওয়াক্ত (কাযা বা বিরতি নয়)।
     */
