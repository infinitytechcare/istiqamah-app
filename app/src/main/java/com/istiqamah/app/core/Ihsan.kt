enum class SunnahSlot(val code: Int, val bn: String, val rakat: Int, val twelve: Boolean, val after: Prayer?) {
    FAJR_BEFORE(1, "ফজরের আগে", 2, true, Prayer.FAJR),
    DHUHR_BEFORE(2, "যোহরের আগে", 4, true, Prayer.DHUHR),
    DHUHR_AFTER(3, "যোহরের পরে", 2, true, Prayer.DHUHR),
    MAGHRIB_AFTER(4, "মাগরিবের পরে", 2, true, Prayer.MAGHRIB),
    ISHA_AFTER(5, "ইশার পরে", 2, true, Prayer.ISHA),
    WITR(6, "বিতর", 3, false, Prayer.ISHA),
    TAHAJJUD(7, "তাহাজ্জুদ", 0, false, null),
    DUHA(8, "ইশরাক/দোহা", 0, false, null);

    companion object {
        fun fromCode(c: Int) = entries.firstOrNull { it.code == c }
        val TWELVE: List<SunnahSlot> get() = entries.filter { it.twelve }
    }
}

/** নামাজে মন কতটা ছিল — এক ট্যাপে */
enum class Khushu(val score: Int, val bn: String) {
    LOW(1, "অন্যমনস্ক ছিলাম"),
    SOME(2, "কিছুটা মন ছিল"),
    GOOD(3, "মনোযোগ ছিল");

    companion object {
        fun fromScore(s: Int) = entries.firstOrNull { it.score == s }
    }
}

