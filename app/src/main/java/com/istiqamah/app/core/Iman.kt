    fun byKey(key: String): ImanLesson? = LESSONS.firstOrNull { it.key == key }

    /** সব প্রশ্নের সঠিক উত্তর দিলে পাঠ সম্পূর্ণ */
    fun passed(lesson: ImanLesson, picks: List<Int?>): Boolean =
        picks.size == lesson.quiz.size && lesson.quiz.indices.all { picks[it] == lesson.quiz[it].answer }

    /** পরের অসম্পূর্ণ পাঠ (ক্রমানুসারে), সব শেষ হলে null */
    fun next(done: Set<String>): ImanLesson? = LESSONS.firstOrNull { it.key !in done }
